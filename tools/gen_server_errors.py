# Kullanım: python3 tools/gen_server_errors.py  (proje kökünden) → lib/core/juzzio_server_errors.dart
# Yeni bir RAISE EXCEPTION kodu eklendiğinde M sözlüğüne Türkçe/İngilizce metniyle eklenmelidir.
import re, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sql = open(os.path.join(ROOT, 'supabase', 'juzzio_database.sql'), encoding='utf-8').read()
tokens = sorted({t.split(':')[0] for t in re.findall(r"RAISE EXCEPTION '([^']*)'", sql)})
missing = [t for t in tokens if t not in M]
if missing:
    raise SystemExit('Metni eksik sunucu hata kodları: ' + ', '.join(missing))
def esc(s): return s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$')
keys = sorted(M.keys(), key=lambda k: -len(k))
out = ['// GENERATED by tools/gen_server_errors.py — sunucu hata kodları → anlaşılır metin (v1.2.9).',
       '// "P0001" (RAISE EXCEPTION) hatalarının kullanıcıya çıplak kodla görünmesini engeller.',
       '// Metinler trEn ile yazılır; dil paketi aracı bunları 140+ dile çevirir.', '',
       "import 'app_theme_and_locale.dart';", '',
       '/// Bilinen sunucu hata kodları (en uzundan kısaya; ilk eşleşen kazanır)',
       'const List<String> kJuzzioServerErrorCodes = [']
out += [f"  '{k}'," for k in keys]
out.append('];')
out.append('''
/// Ham hata metninde bilinen bir sunucu kodu varsa yerelleştirilmiş açıklamayı döndürür.
String? juzzioServerErrorText(String raw) {
  for (final k in kJuzzioServerErrorCodes) {
    if (raw.contains(k)) return _text(k);
  }
  return null;
}

String _text(String code) {
  final app = JuzzioAppController.instance;
  switch (code) {''')
for k in keys:
    tr, en = M[k]
    out.append(f"    case '{k}':\n      return app.trEn('{esc(tr)}', '{esc(en)}');")
out.append("  }\n  return app.trEn('İşlem tamamlanamadı. Lütfen tekrar dene.', 'The action could not be completed. Please try again.');\n}\n")
open(os.path.join(ROOT, 'lib', 'core', 'juzzio_server_errors.dart'), 'w', encoding='utf-8').write('\n'.join(out))
print('ok', len(keys))
